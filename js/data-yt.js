/* -------- أدوات مساعدة --------
   يحوّل المدة العربية إلى صيغة د:ث  مثال: "6 دقائق و13 ثانية" -> "6:13" */
function ytDur(label) {
  if (!label) return "";
  let mm = 0, ss = 0;
  const m = label.match(/(\d+)\s*(دقيقة|دقيقتان|دقائق)/);
  if (m) mm = +m[1];
  else if (/دقيقتان/.test(label)) mm = 2;
  else if (/دقيقة/.test(label)) mm = 1;

  const s = label.match(/(\d+)\s*(ثانية|ثانيتان|ثوان|ثواني|ثانيتين)/);
  if (s) ss = +s[1];
  else if (/ثانيتان|ثانيتين/.test(label)) ss = 2;
  else if (/ثانية/.test(label)) ss = 1;

  if (!mm && !ss) return "";
  return mm + ":" + String(ss).padStart(2, "0");
}

/* يحوّل عنوان يوتيوب (مع المدة في نهايته) إلى عنوان نظيف */
function ytTitle(raw) {
  if (!raw) return "";
  return String(raw)
    .replace(/\s*\d+\s*(?:دقيقة|دقيقتان|دقائق)\s*(?:و\s*)?(?:\d+\s*)?(?:ثانية|ثانيتان|ثوان|ثواني|ثانيتين)?\s*$/, "")
    .replace(/\s*(?:و\s*)?(?:\d+\s*)?(?:ثانية|ثانيتان|ثوان|ثواني|ثانيتين)\s*$/, "")
    .replace(/\s*\d+\s*(?:دقيقة|دقيقتان|دقائق)\s*$/, "")
    .trim();
}

/* جلب بيانات المقطع من الخريطة */
function ytInfo(key) {
  const e = YT_MAP[key];
  if (!e) return null;
  return { id: e[0], durLabel: e[1], dur: ytDur(e[1]), title: ytTitle(e[2]), rawTitle: e[2] };
}
